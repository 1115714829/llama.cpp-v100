class Locale {
 language = $state<'zh-CN' | 'en'>('zh-CN');
 restore() {
  try { this.language = localStorage.getItem('ui-language') === 'en' ? 'en' : 'zh-CN'; } catch { /* Storage is optional. */ }
  document.documentElement.lang = this.language;
 }
 toggle() {
  this.language = this.language === 'en' ? 'zh-CN' : 'en';
  document.documentElement.lang = this.language;
  try { localStorage.setItem('ui-language', this.language); } catch { /* Storage is optional. */ }
 }
 text(zh: string, en: string) { return this.language === 'en' ? en : zh; }
}
export const locale = new Locale();
export const t = (zh: string, en: string) => locale.text(zh, en);

